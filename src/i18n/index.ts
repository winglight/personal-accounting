const I18nContext = createContext<{ language: Language; t: (key: string, vars?: Record<string, string>) => string }>({
  language: 'zh',
  t: (key) => key,
});

const interpolate = (template: string, vars?: Record<string, string>) => {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => vars[key] ?? '');
};

export const I18nProvider: React.FC<{ language: Language; children: React.ReactNode }> = ({ language, children }) => {
  const t = useMemo(() => (key: string, vars?: Record<string, string>) => {
    const dict = dictionaries[language] || dictionaries.en;
    const value = dict[key] ?? dictionaries.en[key] ?? key;
    return interpolate(value, vars);
  }, [language]);

  return React.createElement(I18nContext.Provider, { value: { language, t } }, children);
};

export const useI18n = () => useContext(I18nContext);
